-- Every entity table gets the AbstractEntity columns: a generated BIGINT id and a version for optimistic locking.
-- Backward compatible with the previous application version: its inserts get id and version from the defaults,
-- and Hibernate accepts its Integer space ids on the BIGINT columns.
-- PostgreSQL runs this whole migration in one transaction: it applies completely or not at all.

-- Fail fast (and retry the deploy) rather than queue behind live traffic for a table lock.
SET LOCAL lock_timeout = '5s';

ALTER TABLE users               ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE vehicles            ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE wallets             ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE parking_spaces      ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE reservations        ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE wallet_transactions ADD COLUMN version BIGINT NOT NULL DEFAULT 0;

-- wallets: own surrogate id like every other table; user_id stays one-to-one through a unique constraint.
ALTER TABLE wallets ADD COLUMN id BIGSERIAL;  -- numbers the existing rows
ALTER TABLE wallets DROP CONSTRAINT wallets_pkey;
ALTER TABLE wallets ADD CONSTRAINT wallets_pkey PRIMARY KEY (id);
ALTER TABLE wallets ADD CONSTRAINT uk_wallets_user_id UNIQUE (user_id);

-- parking_spaces: BIGINT identity like every other id. Space numbers 1-80 are kept; the referencing column
-- follows. Constraint names (reservations_space_id_fkey, uk_reservations_space_date) are unchanged.
ALTER TABLE reservations   ALTER COLUMN space_id TYPE BIGINT;
ALTER TABLE parking_spaces ALTER COLUMN id TYPE BIGINT;
ALTER TABLE parking_spaces ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('parking_spaces', 'id'), (SELECT max(id) FROM parking_spaces));
